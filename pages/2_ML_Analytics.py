
import streamlit as st
import requests
import pandas as pd

# ---------------- PAGE CONFIG ----------------

st.set_page_config(
    page_title="ML Analytics",
    page_icon="🤖",
    layout="wide"
)

# ---------------- API CONFIG ----------------

import os

API_URL = os.getenv(
    "API_BASE_URL",
    "http://api:8000"
).rstrip("/")


# ---------------- FETCH ANALYTICS ----------------

@st.cache_data(ttl=30)
def fetch_analytics():

    response = requests.get(
        f"{API_URL}/ml/analytics",
        timeout=30
    )

    response.raise_for_status()

    data = response.json()

    return data["analytics"]


# ---------------- HEADER ----------------

st.title("🤖 ML Prediction Analytics")

st.caption(
    "Monitor task predictions generated by the SVM model."
)

st.divider()


# ---------------- REFRESH ----------------

if st.button("🔄 Refresh Analytics"):

    fetch_analytics.clear()
    st.rerun()


# ---------------- ANALYTICS ----------------

try:

    analytics = fetch_analytics()

    total = analytics["total_predictions"]
    done = analytics["done_predictions"]
    not_done = analytics["not_done_predictions"]
    completion = analytics["completion_percentage"]

    # ---------------- METRICS ----------------

    st.subheader("Prediction Overview")

    col1, col2, col3, col4 = st.columns(4)

    col1.metric(
        "Total Predictions",
        total
    )

    col2.metric(
        "Done",
        done
    )

    col3.metric(
        "Not Done",
        not_done
    )

    col4.metric(
        "Completion Rate",
        f"{completion}%"
    )

    st.divider()

    # ---------------- CHART ----------------

    st.subheader("Prediction Status Distribution")

    chart_data = pd.DataFrame({
        "Status": ["Done", "Not Done"],
        "Predictions": [done, not_done]
    })

    st.bar_chart(
        chart_data,
        x="Status",
        y="Predictions",
        color="#3B82F6"
    )

    st.divider()

    # ---------------- SUMMARY ----------------

    st.subheader("Prediction Summary")

    col1, col2 = st.columns(2)

    with col1:

        st.write("**Completed Tasks**")

        st.progress(
            min(completion / 100, 1.0)
        )

        st.caption(f"{done} completed predictions")

    with col2:

        st.write("**Incomplete Tasks**")

        incomplete_percentage = (
            not_done / total * 100 if total > 0 else 0
        )

        st.progress(
            min(incomplete_percentage / 100, 1.0)
        )

        st.caption(f"{not_done} incomplete predictions")

    st.success(
        "Analytics successfully loaded from FastAPI!"
    )

except requests.exceptions.RequestException as e:

    st.error(f"FastAPI connection error: {e}")

except (KeyError, TypeError, ValueError) as e:

    st.error(f"Invalid analytics response: {e}")
